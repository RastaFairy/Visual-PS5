'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = rel => fs.readFileSync(path.join(root, rel), 'utf8');
const html = read('index.html');
const app = read('app.js');
const server = read('runtime/server.ps1');

assert.match(html, /runtime\/unicode-fonts\.js\?v=1\.1\.9/);
assert.match(html, /runtime\/layer-model\.js\?v=1\.1\.9/, 'layer model must remain enabled');
assert.match(html, /assetFileInput[^>]*\.ttf/, 'asset picker must accept TTF fonts');
assert.match(app, /fontAssetId:''/, 'new projects must initialise the optional font selection');
assert.match(app, /if\(!project\.assets\.length\)\{project\.fontAssetId='';/, 'removing the last font asset must clear its selection');
assert.match(app, /function renderUnicodeFontPicker\(\)/);
assert.match(app, /PS5HSUnicodeFonts\.prepareFontAsset\(selectedFont\)/);
assert.match(app, /PS5HSUnicodeFonts\.collectCodepoints\(data\)/);
assert.match(app, /nativeAssets,overwriteExisting:[^}]*nativeFont\}/, 'the selected font must be sent to the build API');
assert.match(server, /function PrepareNativeUnicodeFonts\(/, 'server font preparation must exist');
const buildStart = server.indexOf('function BuildNativeVisualProject(');
const buildEnd = server.indexOf('\nfunction SaveProject(', buildStart);
assert.ok(buildStart >= 0 && buildEnd > buildStart, 'could not isolate native build function');
const build = server.slice(buildStart, buildEnd);
const assetsAt = build.indexOf('$assetResult = WriteNativeVisualAssets $Body $projectRoot');
const unicodeAt = build.indexOf('PrepareNativeUnicodeFonts $Body $projectRoot $backend');
const compileAt = build.indexOf('$build = BuildNativeProject $projectRoot');
assert.ok(assetsAt >= 0 && unicodeAt > assetsAt && compileAt > unicodeAt, 'Unicode atlas preparation must happen before native compilation');
assert.match(server, /PS5HS_CUSTOM_UNICODE_FONT_BEGIN/, 'normal upstream baking must not overwrite selected custom atlases');
assert.match(server, /tools\/font-baker\/bake_font\.cpp/);
console.log('PASS Unicode integration: UI selection, API payload, backend preparation, build ordering and atlas preservation are connected');
